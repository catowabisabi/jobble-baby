# Jobble Baby

> Fewer clicks, more presence.

A calm, privacy-first baby tracking app designed for HK/Taiwan/Singapore/Malaysia Chinese-speaking parents. All data stays on your device — no account, no ads, no data selling.

## App Overview

Jobble Baby is a comprehensive infant care companion covering 68 interactive tabs:

- **Sleep**: Sleep architecture, sleep training, sleep debt, sleep association, circadian rhythm
- **Feeding**: Bottle feeding, milk prep, milk transfer, cup feeding, feeding readiness, solid food
- **Growth**: WHO growth chart, fontanelle tracking, asymmetric growth, growth montage
- **Health**: Allergens, jaundice threshold, gut-brain axis, colic relief, teething, thermal regulation
- **Development**: Milestones, reflex tracker, sensory integration, critical periods, vestibular assessment
- **Caregiver**: Stress cascade, window of tolerance, caregiver fatigue, habit reset, shift handoff
- **Clinical**: Clinician portal, doctor visit, pediatric report, procedure recovery
- **Safety**: Home safety, safety audit, iot-security, gear check

## Tech Stack

- **Framework**: Expo SDK 56 + React Native
- **Language**: TypeScript (strict mode)
- **Navigation**: expo-router (tab-based, 68 tabs)
- **Storage**: AsyncStorage (all data on-device)
- **i18n**: en.json + zh.json (full bilingual coverage)
- **UI**: Dark theme, one-hand friendly, WCAG 2.1 AA accessibility

